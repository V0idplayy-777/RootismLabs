import assert from 'node:assert/strict';
import { tableToDataset, transformTableRow, datasetToNative, nativeToDataset } from '../js/data/import.js';
import { auditDataset, auditModelDataset } from '../js/data/preflight.js';
import { graphForDataset } from '../js/presets/from-data.js';
import { analyze } from '../js/core/model.js';
import { Trainer } from '../js/core/train.js';
import { TASKS } from '../js/core/tasks.js';
import { Node } from '../js/core/tensor.js';

const rows = Array.from({length: 30}, (_, i) => ({ text: 'sample words ' + i, value: i * 2 + 1, category: i < 27 ? 'known' : 'heldout', group: 'person' + Math.floor(i / 3), label: i % 2 ? 'positive' : 'negative' }));
const ds = tableToDataset({ rows, labelColumn: 'label', groupColumn: 'group', splitSeed: 8 });
assert.equal(ds.source, 'imported');
assert.deepEqual(ds.labels, ['negative', 'positive']);
assert(!ds.featureSpec.columns.some(c => c.column === 'group'));
const sets = Object.values(ds.splits).map(indices => new Set(Array.from(indices, i => ds.groups[i])));
for (let i = 0; i < 3; i++) for (let j = i + 1; j < 3; j++) for (const group of sets[i]) assert(!sets[j].has(group), 'groups must not cross splits');
for (let i = 0; i < ds.count; i++) assert.deepEqual(Array.from(transformTableRow(rows[i], ds.featureSpec)), Array.from(ds.x.subarray(i * ds.xShape[0], (i+1) * ds.xShape[0])));
const restored = nativeToDataset(datasetToNative(ds));
assert.deepEqual(Array.from(transformTableRow(rows[0], restored.featureSpec)), Array.from(ds.x.subarray(0, ds.xShape[0])));
assert.equal(auditDataset(ds).errors.length, 0);
const graph = graphForDataset(ds);
assert(analyze(graph).valid);
assert.equal(auditModelDataset(graph, ds, 'binary', analyze(graph)).errors.length, 0);
assert(auditModelDataset({...graph, input: {shape:[1]}}, ds, 'binary', analyze(graph)).errors.length);
const saved = ds.splits.train; ds.splits.train = ds.splits.val;
assert(auditDataset(ds).errors.some(x => x.includes('training split changed'))); ds.splits.train = saved;
assert.throws(() => tableToDataset({ rows: [{ x: 1, label: '' }, { x: 2, label: 'a' }], labelColumn: 'label' }), /missing values/);
// Metrics at a fixed operating threshold must not optimize on the test labels.
const model = { forward(x) { return new Node(Float32Array.from(x.d, () => -0.4), [x.shape[0], 1]); } };
const evaluation = TASKS.binary.metrics(model, ds, ds.splits.test, { decisionThreshold: 0.5 });
assert.equal(evaluation.scalars.best_threshold, 0.5);
assert.equal(evaluation.scalars.recall, 0);
const trainer = new Trainer({ spec: graph, dataset: ds, taskKey: ds.task, config: { epochs: 2, batchSize: 4, schedule: { name: 'constant' }, optimizer: { name: 'adam', lr: 0.005 } } });
const result = await trainer.run();
assert.equal(result.state, 'completed');
assert(Number.isFinite(result.metrics.test.loss));
console.log('train-only preprocessing, grouped splits, fixed-threshold evaluation and training path passed');
const { tablePreprocessingModule, buildBundle } = await import('../js/export/bundle.js');
const moduleText = tablePreprocessingModule(ds.featureSpec);
const runtime = await import('data:text/javascript;base64,' + Buffer.from(moduleText).toString('base64'));
for (const row of rows) assert.deepEqual(Array.from(runtime.preprocess(row)), Array.from(transformTableRow(row, ds.featureSpec)));
const bundle = buildBundle({ dataset: ds, includeDataset: false });
assert(bundle.entries.some(e => e.name === 'preprocessing/table.mjs'));
console.log('standalone exported preprocessing matches training vectors');
const { rocCurve, wilsonInterval } = await import('../js/core/metrics.js');
assert(Math.abs(wilsonInterval(21, 21).lower - 0.84536) < 0.0001);
assert(Number.isNaN(wilsonInterval(0, 0).lower));
assert.equal(rocCurve([0.5, 0.5], [1, 0]).auc, 0.5, 'tied positive/negative scores must receive half credit');
assert.equal(rocCurve([0.5, 0.5], [0, 1]).auc, 0.5, 'AUC must not depend on input order');
assert(Number.isNaN(rocCurve([0.5], [1]).auc), 'AUC is undefined without both classes');
const { buildEvaluator } = await import('../js/export/pipeline.js');
assert.equal(buildEvaluator({ spec: graph, dataset: ds, taskKey: 'binary' }).split, 'val', 'precision selection must default to validation');
const temporalRows = Array.from({ length: 40 }, (_, i) => ({ x: i, category: i < 28 ? (i % 2 ? 'a' : 'b') : 'unseen', label: i % 2 ? 'yes' : 'no' }));
const temporal = tableToDataset({ rows: temporalRows, labelColumn: 'label', splitMethod: 'temporal' });
const altered = temporalRows.map((row, i) => i < 28 ? row : { ...row, x: 100000 + i, category: 'other' });
const temporal2 = tableToDataset({ rows: altered, labelColumn: 'label', splitMethod: 'temporal' });
assert.deepEqual(temporal.featureSpec.columns, temporal2.featureSpec.columns, 'held-out rows must not fit preprocessing');
assert.deepEqual(temporal.splits.train, temporal2.splits.train);
assert.equal(temporal.featureSpec.columns.find(c => c.column === 'category').vocab.includes('unseen'), false);
const autoLabel = tableToDataset({ rows: temporalRows, labelColumn: null });
assert.equal(autoLabel.provenance.labelColumn, 'label', 'blank UI label must trigger inference');
const { auditModelDataset: checkModel } = await import('../js/data/preflight.js');
for (const task of ['binary', 'multiclass', 'multilabel', 'regression']) {
  const d = { name:'example', task, xShape:[20], yShape:[task === 'multilabel' ? 3 : 1], labels:task === 'multiclass' ? ['a','b','c'] : [] };
  const g = graphForDataset(d), info = analyze(g);
  assert(info.valid); assert.equal(checkModel(g, d, task, info).errors.length, 0);
}
const continuousRows = Array.from({ length: 50 }, (_, i) => ({ x: i * 2, value: i + 0.3 }));
const continuous = tableToDataset({ rows: continuousRows, labelColumn: 'value', task: 'regression' });
assert.equal(continuous.splitMethod, 'random');
assert(continuous.splits.val.length > 0 && continuous.splits.test.length > 0, 'continuous targets must not be treated as separate strata');
